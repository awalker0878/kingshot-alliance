// Preserve the prior loader's deep-merge precedence for overlapping nested keys.
function mergeCatalogue(base: MessageCatalogue, overlay: MessageCatalogue): MessageCatalogue {
  const result: MessageCatalogue = { ...base };
  for (const [key, value] of Object.entries(overlay)) {
    if (typeof value === 'string') {
      result[key] = value;
      continue;
    }
    const existing = result[key];
    result[key] = mergeCatalogue(typeof existing === 'object' ? existing : {}, value);
  }
  return result;
}

