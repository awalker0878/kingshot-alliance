type Values<K extends readonly string[]> = { readonly [I in keyof K]: string };
type RosterValues = Values<typeof rosterKeys>;
type RosterKey = (typeof rosterKeys)[number];

export type RosterMessageTree = { roster: Record<RosterKey, string> };

function section<K extends readonly string[]>(
  keys: K,
  values: Values<K>,
): Record<K[number], string> {
  return Object.fromEntries(keys.map((key, index) => [key, values[index]])) as Record<
    K[number],
    string
  >;
}

function locale(values: RosterValues): RosterMessageTree {
  return { roster: section(rosterKeys, values) };
}

