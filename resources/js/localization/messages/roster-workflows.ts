type Values<K extends readonly string[]> = { readonly [I in keyof K]: string };
type ImportKey = (typeof importKeys)[number];
type HistoryKey = (typeof historyKeys)[number];

type WorkflowValues = {
  import: Values<typeof importKeys>;
  history: Values<typeof historyKeys>;
};

export type RosterWorkflowMessageTree = {
  rosterImport: Record<ImportKey, string>;
  rosterHistory: Record<HistoryKey, string>;
};

function section<K extends readonly string[]>(
  keys: K,
  values: Values<K>,
): Record<K[number], string> {
  return Object.fromEntries(keys.map((key, index) => [key, values[index]])) as Record<
    K[number],
    string
  >;
}

function locale(values: WorkflowValues): RosterWorkflowMessageTree {
  return {
    rosterImport: section(importKeys, values.import),
    rosterHistory: section(historyKeys, values.history),
  };
}

