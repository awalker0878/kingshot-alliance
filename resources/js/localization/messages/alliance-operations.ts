type Values<K extends readonly string[]> = { readonly [I in keyof K]: string };
type OverviewValues = Values<typeof overviewKeys>;
type EventValues = Values<typeof eventKeys>;
type StatusValues = Values<typeof statusKeys>;
type OverviewKey = (typeof overviewKeys)[number];
type EventKey = (typeof eventKeys)[number];
type StatusKey = (typeof statusKeys)[number];

export type AllianceOperationsTree = {
  allianceOperations: {
    overview: Record<OverviewKey, string>;
    events: Record<EventKey, string>;
    status: Record<StatusKey, string>;
  };
};

function section<K extends readonly string[]>(
  keys: K,
  values: Values<K>,
): Record<K[number], string> {
  return Object.fromEntries(keys.map((key, index) => [key, values[index]])) as Record<
    K[number],
    string
  >;
}

function locale(
  overview: OverviewValues,
  events: EventValues,
  status: StatusValues,
): AllianceOperationsTree {
  return {
    allianceOperations: {
      overview: section(overviewKeys, overview),
      events: section(eventKeys, events),
      status: section(statusKeys, status),
    },
  };
}

