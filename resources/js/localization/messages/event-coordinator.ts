type Values<K extends readonly string[]> = { readonly [I in keyof K]: string };
type CoordinatorValues = Values<typeof coordinatorKeys>;
type CoordinatorKey = (typeof coordinatorKeys)[number];

export type EventCoordinatorTree = {
  eventCoordinator: Record<CoordinatorKey, string>;
};

function locale(values: CoordinatorValues): EventCoordinatorTree {
  return {
    eventCoordinator: Object.fromEntries(
      coordinatorKeys.map((key, index) => [key, values[index]]),
    ) as Record<CoordinatorKey, string>,
  };
}

