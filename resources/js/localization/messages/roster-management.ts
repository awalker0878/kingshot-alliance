type Values<K extends readonly string[]> = { readonly [I in keyof K]: string };
type MessageKey = (typeof keys)[number];
type MessageValues = Values<typeof keys>;

export type RosterManagementMessageTree = { rosterManage: Record<MessageKey, string> };

function section<K extends readonly string[]>(
  names: K,
  values: Values<K>,
): Record<K[number], string> {
  return Object.fromEntries(names.map((key, index) => [key, values[index]])) as Record<
    K[number],
    string
  >;
}

function locale(values: MessageValues): RosterManagementMessageTree {
  return { rosterManage: section(keys, values) };
}

